def _mapa(trazos: str, color: str, tam: int) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{trazos}</svg>')
    render = QSvgRenderer(QByteArray(svg.encode()))
    mapa = QPixmap(tam * 2, tam * 2)  # el doble de resolución: se ve nítido en pantallas densas
    mapa.fill(Qt.GlobalColor.transparent)
    pintor = QPainter(mapa)
    render.render(pintor, QRectF(0, 0, tam * 2, tam * 2))
    pintor.end()
    mapa.setDevicePixelRatio(2)
    return mapa


def icono(nombre: str, color: str | None = None, tam: int = 20, color_activo: str | None = None) -> QIcon:
    """Icono del color secundario del tema; marcado (seleccionado) o con el cursor encima, del color principal."""
    colores = tema.colores()
    color = color or colores["texto_tenue"]
    color_activo = color_activo or colores["texto_fuerte"]
    trazos = _TRAZOS.get(nombre, _TRAZOS["Dashboard"])
    ic = QIcon()
    ic.addPixmap(_mapa(trazos, color, tam), QIcon.Mode.Normal, QIcon.State.Off)
    ic.addPixmap(_mapa(trazos, color_activo, tam), QIcon.Mode.Normal, QIcon.State.On)
    return ic
