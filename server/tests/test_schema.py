import json
import subprocess
import sys
from pathlib import Path

import oracledb
import pytest

ROOT = Path(__file__).resolve().parents[2]
CONTEO = "CONT-2026-11"


def _scalar(db, sql, **binds):
    cur = db.cursor()
    cur.execute(sql, binds)
    return cur.fetchone()[0]


def _insert_transito(db, uuid="dev-test", seq=1, raw="REC|x"):
    """Inserta una fila de staging sin ID y devuelve el ID generado por el trigger."""
    cur = db.cursor()
    out = cur.var(int)
    cur.execute(
        "INSERT INTO captura_transito (uuid_dispositivo, seq, datos_raw) "
        "VALUES (:u, :s, :r) RETURNING id_transito INTO :id",
        u=uuid,
        s=seq,
        r=raw,
        id=out,
    )
    return int(out.getvalue()[0])


def test_seed_counts(db):
    assert _scalar(db, "SELECT COUNT(*) FROM productos") == 60
    assert (
        _scalar(db, "SELECT COUNT(*) FROM stock_sistema WHERE id_conteo = :c", c=CONTEO)
        == 58
    )
    assert _scalar(db, "SELECT COUNT(*) FROM ubicaciones") == 12
    assert _scalar(db, "SELECT COUNT(*) FROM conteos WHERE estado = 'ABIERTO'") == 1
    assert _scalar(db, "SELECT COUNT(*) FROM captura_transito") == 0


def test_duplicate_device_seq_rejected(db):
    _insert_transito(db, uuid="dev-dup", seq=1)
    with pytest.raises(oracledb.DatabaseError, match="ORA-00001"):
        _insert_transito(db, uuid="dev-dup", seq=1)


def test_invalid_estado_rejected(db):
    with pytest.raises(oracledb.DatabaseError, match="ORA-02290"):
        db.cursor().execute(
            "INSERT INTO captura_transito (uuid_dispositivo, seq, datos_raw, estado) "
            "VALUES ('dev-x', 1, 'REC|x', 'X')"
        )


def test_id_autogenerated(db):
    first = _insert_transito(db, seq=1)
    second = _insert_transito(db, seq=2)
    assert second == first + 1


def test_varchar_limits_are_in_characters(db):
    tid_ok = _insert_transito(db, seq=1)
    tid_long = _insert_transito(db, seq=2)
    ubic = _scalar(db, "SELECT MIN(cod_ubicacion) FROM ubicaciones")
    sku = _scalar(db, "SELECT MIN(sku) FROM productos")
    sql = (
        "INSERT INTO registros_procesados "
        "(id_transito, id_conteo, cod_ubicacion, sku, cantidad, operador, fecha_captura) "
        "VALUES (:t, :c, :u, :s, 1, :op, SYSTIMESTAMP)"
    )
    # 60 'Ñ' = 120 bytes en UTF-8: solo cabe si la longitud es en caracteres.
    db.cursor().execute(sql, t=tid_ok, c=CONTEO, u=ubic, s=sku, op="Ñ" * 60)
    with pytest.raises(oracledb.DatabaseError, match="ORA-12899"):
        db.cursor().execute(sql, t=tid_long, c=CONTEO, u=ubic, s=sku, op="Ñ" * 61)


def _run_gen_seed(tmp_path: Path, name: str) -> tuple[bytes, bytes]:
    sql = tmp_path / f"{name}.sql"
    truth = tmp_path / f"{name}.json"
    subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools" / "gen_seed.py"),
            "--seed",
            "42",
            "--sql",
            str(sql),
            "--truth",
            str(truth),
        ],
        check=True,
        capture_output=True,
    )
    return sql.read_bytes(), truth.read_bytes()


def test_gen_seed_is_deterministic(tmp_path):
    first = _run_gen_seed(tmp_path, "a")
    second = _run_gen_seed(tmp_path, "b")
    assert first == second
    # Lo versionado en el repo es exactamente lo que genera la semilla 42.
    assert first[0] == (ROOT / "db" / "init" / "02_seed.sql").read_bytes()
    assert first[1] == (ROOT / "tools" / "truth.json").read_bytes()


def test_truth_json_covers_all_seeded_skus(db):
    truth = json.loads((ROOT / "tools" / "truth.json").read_text(encoding="utf-8"))
    truth_skus = {row["sku"] for row in truth["fisico"]}
    cur = db.cursor()
    cur.execute("SELECT sku FROM productos")
    all_skus = {row[0] for row in cur}
    assert len(all_skus) == 60
    assert truth_skus == all_skus
    cur.execute(
        "SELECT sku FROM productos MINUS "
        "SELECT sku FROM stock_sistema WHERE id_conteo = :c",
        c=CONTEO,
    )
    outside_snapshot = {row[0] for row in cur}
    assert len(outside_snapshot) == 2
    assert outside_snapshot <= truth_skus
